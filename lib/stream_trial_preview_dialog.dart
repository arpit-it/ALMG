import 'dart:convert';
import 'package:flutter/material.dart';

class StreamTrialPreviewDialog extends StatefulWidget {
  const StreamTrialPreviewDialog({super.key, required this.run, required this.request});
  final Map<String, dynamic> run;
  final Future<Map<String, dynamic>> Function(String, Map<String, dynamic>) request;
  @override State<StreamTrialPreviewDialog> createState() => _StreamTrialPreviewDialogState();
}

class _StreamTrialPreviewDialogState extends State<StreamTrialPreviewDialog> {
  final _prompt = TextEditingController();
  Map<String, dynamic>? _result;
  bool _busy = false;
  String? _error;
  @override void dispose() { _prompt.dispose(); super.dispose(); }
  Future<void> _generate() async {
    setState(() { _busy = true; _error = null; _result = null; });
    try {
      final result = await widget.request('/decoder-stream-training-runs/${widget.run['id']}/preview', {
        'confirmed': true, 'reviewed_revision': widget.run['revision'], 'prompt': _prompt.text, 'max_new_tokens': 12,
      });
      if (mounted) setState(() { _result = result; _busy = false; });
    } catch (error) { if (mounted) setState(() { _error = error.toString(); _busy = false; }); }
  }
  Future<void> _history() async {
    setState(() { _busy = true; _error = null; });
    try {
      final records = (await widget.request('/decoder-stream-training-runs/${widget.run['id']}/previews', {
        'confirmed': true, 'reviewed_revision': widget.run['revision'],
      }))['previews'] as List;
      if (!mounted) return;
      setState(() => _busy = false);
      final selected = await showDialog<Map<String, dynamic>>(context: context, builder: (context) => SimpleDialog(
        title: const Text('Saved private text previews'), children: [
          if (records.isEmpty) const Padding(padding: EdgeInsets.all(16), child: Text('No saved text previews.')),
          for (final record in records) SimpleDialogOption(onPressed: () => Navigator.pop(context, Map<String, dynamic>.from(record as Map)),
            child: Text('${(record['id'] as String).substring(0, 8)} · ${record['generated_token_ids'].length} generated IDs')),
        ]));
      if (selected != null && mounted) setState(() { _result = selected; _prompt.text = selected['prompt'] as String; });
    } catch (error) { if (mounted) setState(() { _error = error.toString(); _busy = false; }); }
  }
  @override Widget build(BuildContext context) => AlertDialog(
    title: const Text('Private streamed model preview'), scrollable: true,
    content: SizedBox(width: 620, child: Column(mainAxisSize: MainAxisSize.min, crossAxisAlignment: CrossAxisAlignment.start, children: [
      const Text('This short trial has not established usable model quality. Output may be meaningless. No model release is approved. '
        'Generate uses the saved model and tokenizer on this machine and saves your exact prompt and output privately. '
        'Enter at most 16 saved-tokenizer IDs; longer or unsupported prompts are rejected. Twelve greedy token IDs are generated with a sliding context. '
        'Generated byte sequences use replacement characters when needed for display. No training or external request runs.'),
      TextField(controller: _prompt, enabled: !_busy, maxLength: 4096, decoration: const InputDecoration(labelText: 'Exact local prompt')),
      if (_busy) const LinearProgressIndicator(),
      if (_error != null) Text(_error!),
      if (_result != null) ...[
        const Text('Generated preview'),
        SelectableText((_result!['completion'] as String).trim().isEmpty ? '(Whitespace-only output)' : _result!['completion'] as String),
        ExpansionTile(title: const Text('View saved preview record'), children: [
          SelectableText(const JsonEncoder.withIndent('  ').convert(_result)),
        ]),
      ],
    ])), actions: [
      TextButton(onPressed: _busy ? null : _history, child: const Text('Saved text previews')),
      TextButton(onPressed: _busy ? null : _generate, child: const Text('Generate and save private preview')),
      TextButton(onPressed: _busy ? null : () => Navigator.pop(context), child: const Text('Close')),
    ]);
}
