"""Explicit model-use wrapper for a separately reviewed, lossless fitted codec."""
from copy import deepcopy
import re

if __package__:
    from .decoder_tokenizer import Tokenizer
    from .decoder_special_tokens import SpecialTokenizer, restore_base
    from .run_manifest import digest
else:
    from decoder_tokenizer import Tokenizer
    from decoder_special_tokens import SpecialTokenizer, restore_base
    from run_manifest import digest

FORMAT = 'almg-reviewed-model-tokenizer-v1'


class ModelTokenizer(Tokenizer):
    def __init__(self, codec, selection):
        if not isinstance(codec, dict):
            raise ValueError('Provide a versioned fitted codec artifact.')
        self.codec = SpecialTokenizer.restore(codec) if codec.get('format') == 'almg-special-tokenizer-v1' else restore_base(codec)
        if not 4 <= len(self.codec.pieces) <= 256:
            raise ValueError('Model tokenizer requires 4 to 256 actual IDs, including special tokens.')
        expected = {'parent_dataset_id':32, 'experiment_id':32, 'parent_manifest_sha256':64,
                    'experiment_revision':64, 'approval_sha256':64}
        if (not isinstance(selection, dict) or set(selection) != set(expected)
                or any(not isinstance(selection[key], str) or re.fullmatch('[a-f0-9]{'+str(size)+'}', selection[key]) is None
                       for key, size in expected.items())):
            raise ValueError('Model tokenizer requires exact dataset, experiment and selection approval bindings.')
        self.selection = deepcopy(selection)

    @property
    def vocabulary(self):
        # Stable ID descriptors; codec pieces/merges and controls live in the artifact.
        return [f'<token-id-{index}>' for index in range(len(self.codec.pieces))]

    def encode(self, text):
        if hasattr(self.codec, 'uncovered') and self.codec.uncovered(text):
            raise ValueError('Model input must encode losslessly; UNK replacement is unavailable for this model wrapper.')
        tokens = self.codec.encode(text)
        if not tokens or any(type(value) is not int or not 0 <= value < len(self.vocabulary) for value in tokens):
            raise ValueError('Model tokenizer emitted invalid IDs.')
        return tokens

    def decode(self, tokens):
        try:
            return self.codec.decode(tokens)
        except UnicodeDecodeError:
            # A generated byte sequence can be invalid UTF-8, unlike reviewed inputs.
            # The strict codec has already checked bounds before attempting decode.
            return b''.join(self.codec.pieces[value] for value in tokens).decode('utf-8', errors='replace')

    def validate_training_documents(self, texts):
        base = self.codec.base if isinstance(self.codec, SpecialTokenizer) else self.codec
        fitted = type(base).fit(texts, base.vocabulary_size)
        if isinstance(self.codec, SpecialTokenizer):
            fitted = SpecialTokenizer(fitted, self.codec.definitions, self.codec.unknown_policy)
        if digest(fitted.artifact()) != digest(self.codec.artifact()):
            raise ValueError('Model tokenizer does not match a training-only fit on this saved partition.')

    def artifact(self):
        return {'format':FORMAT, 'schema_version':1, 'codec':self.codec.artifact(),
                'selection':deepcopy(self.selection), 'scope':'separately_approved_bounded_local_model_trial',
                'input_policy':'lossless_only_no_unknown_replacement',
                'generated_byte_decode':'utf8_replacement_for_preview_only'}

    @classmethod
    def restore(cls, artifact):
        if (not isinstance(artifact, dict) or set(artifact) != {'format','schema_version','codec','selection','scope','input_policy','generated_byte_decode'}
                or artifact.get('format') != FORMAT or type(artifact.get('schema_version')) is not int):
            raise ValueError('Unsupported reviewed model tokenizer artifact.')
        result = cls(artifact['codec'], artifact['selection'])
        if digest(artifact) != digest(result.artifact()):
            raise ValueError('Reviewed model tokenizer policy/version changed.')
        return result
